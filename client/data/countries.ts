const BY_CODE: Record<string, Country> = COUNTRIES.reduce(
  (acc, c) => {
    acc[c.code] = c;
    return acc;
  },
  {} as Record<string, Country>,
);

/** Kod → ülke (bulunamazsa undefined). */
export function getCountry(code?: string | null): Country | undefined {
  if (!code) return undefined;
  return BY_CODE[code.toUpperCase()];
}

/** Kod → Türkçe ad (bulunamazsa kodun kendisi). */
export function getCountryName(code?: string | null): string {
  return getCountry(code)?.name ?? (code || '');
}
